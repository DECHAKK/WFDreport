#!/usr/bin/env node
/**
 * Prepare everything needed to import the demo database into Aiven MySQL from a
 * single Aiven "Service URI".
 *
 *   node database/scripts/prepare-aiven.js "mysql://user:pass@host:port/defaultdb?ssl-mode=REQUIRED"
 *
 * What it does:
 *   1. Parses the URI (host, port, user, password, database).
 *   2. Verifies the host actually resolves and the port accepts TCP connections.
 *   3. Pulls the Aiven CA certificate out of the TLS handshake (no console
 *      download needed) and writes it to ~/Desktop/ca.pem.
 *   4. Writes ~/Desktop/aiven.cnf (mode 600) for the import script and the
 *      production environment variables.
 *
 * The password is never printed; only its length is reported.
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const dns = require('dns').promises;
const net = require('net');
const { execFileSync } = require('child_process');

function fail(message) {
  console.error(`ERROR: ${message}`);
  process.exit(1);
}

function parseUri(uri) {
  let parsed;
  try {
    parsed = new URL(uri);
  } catch (error) {
    fail('รูปแบบ URI ไม่ถูกต้อง (ต้องขึ้นต้นด้วย mysql://)');
  }
  if (!/^mysql:?$/.test(parsed.protocol)) fail(`protocol ไม่ใช่ mysql:// (พบ ${parsed.protocol})`);

  const host = parsed.hostname;
  const port = Number(parsed.port || 3306);
  const user = decodeURIComponent(parsed.username || '');
  const password = decodeURIComponent(parsed.password || '');
  const database = parsed.pathname.replace(/^\//, '') || 'defaultdb';

  if (!host || !user || !password) fail('URI ไม่ครบ (ต้องมี user:password@host)');
  return { host, port, user, password, database };
}

async function assertReachable(host, port) {
  try {
    const addresses = await dns.resolve4(host);
    console.log(`    DNS     : ${host} -> ${addresses.join(', ')}`);
  } catch (error) {
    fail(
      `host "${host}" ไม่มีอยู่ใน DNS (${error.code || error.message})\n`
      + '    Aiven จะถอด DNS record เมื่อ service ถูก power off หรือถูกลบ — '
      + 'ให้เปิด service ใน Console แล้ว copy URI ใหม่',
    );
  }

  await new Promise((resolve, reject) => {
    const socket = net.connect({ host, port, timeout: 8000 });
    socket.once('connect', () => {
      socket.end();
      console.log(`    TCP     : ${host}:${port} เปิดอยู่`);
      resolve();
    });
    socket.once('timeout', () => {
      socket.destroy();
      reject(new Error(`timeout เชื่อมต่อ ${host}:${port}`));
    });
    socket.once('error', (error) => reject(new Error(`${host}:${port} -> ${error.message}`)));
  }).catch((error) => fail(error.message));
}

function fetchCaCertificate(host, port) {
  let output = '';
  try {
    output = execFileSync(
      'openssl',
      ['s_client', '-connect', `${host}:${port}`, '-servername', host, '-showcerts'],
      { input: '', encoding: 'utf8', timeout: 20000, stdio: ['pipe', 'pipe', 'ignore'] },
    );
  } catch (error) {
    // openssl exits non-zero after the handshake in some versions; stdout may still hold the chain
    output = (error.stdout || '').toString();
  }

  const blocks = output.match(/-----BEGIN CERTIFICATE-----[\s\S]*?-----END CERTIFICATE-----/g) || [];
  if (blocks.length === 0) fail('ดึง certificate chain จาก TLS ไม่สำเร็จ (openssl ไม่คืนค่า)');

  // The last certificate in the chain is the Aiven CA that must be trusted.
  const ca = `${blocks[blocks.length - 1]}\n`;
  console.log(`    TLS     : พบ ${blocks.length} certificate → ใช้ใบสุดท้ายเป็น CA`);
  return ca;
}

(async () => {
  const uri = process.argv[2];
  if (!uri) fail('วิธีใช้: node database/scripts/prepare-aiven.js "mysql://user:pass@host:port/defaultdb"');

  const { host, port, user, password, database } = parseUri(uri);
  console.log('==> ตรวจสอบ service');
  console.log(`    host    : ${host}`);
  console.log(`    port    : ${port}`);
  console.log(`    user    : ${user}`);
  console.log(`    password: (${password.length} ตัวอักษร)`);
  console.log(`    database: ${database}`);

  await assertReachable(host, port);

  console.log('==> ดึง CA certificate');
  const ca = fetchCaCertificate(host, port);

  const caPath = path.join(os.homedir(), 'Desktop', 'ca.pem');
  fs.writeFileSync(caPath, ca, { mode: 0o600 });
  console.log(`    เขียนแล้ว: ${caPath}`);

  const cnfPath = path.join(os.homedir(), 'Desktop', 'aiven.cnf');
  const cnf = `# Aiven MySQL — generated by prepare-aiven.js (never commit this file)
[client]
host=${host}
port=${port}
user=${user}
password=${password}
ssl-ca=${caPath}
ssl-mode=VERIFY_CA
`;
  fs.writeFileSync(cnfPath, cnf, { mode: 0o600 });
  console.log(`    เขียนแล้ว: ${cnfPath} (mode 600)`);

  console.log('\n==> ขั้นต่อไป');
  console.log(`    node database/scripts/import-aiven.js --cnf ${cnfPath} --database ${database}`);
  console.log('\n==> ค่า environment สำหรับ Vercel');
  console.log(`    DB_HOST=${host}`);
  console.log(`    DB_PORT=${port}`);
  console.log(`    DB_NAME=${database}`);
  console.log(`    DB_SSL_CA=<เนื้อหาใน ${caPath}>`);
})();
